export function readDesignToken(name, styles = getComputedStyle(document.documentElement)) {
  const value = styles.getPropertyValue(name).trim();
  if (!value) throw new Error(`Missing design token: ${name}`);
  return value;
}
export function readDesignNumber(name, styles = getComputedStyle(document.documentElement)) {
  const value = readDesignToken(name, styles);
  if (!/^-?(?:\d+\.?\d*|\.\d+)(?:px|ms)?$/.test(value)) throw new Error(`Design token must resolve to a numeric value: ${name}`);
  return Number.parseFloat(value);
}

// Entity identity is stable across filtering/reordering; it never encodes health.
export function identityForKey(value) {
  const identities = ['indigo', 'blue', 'violet', 'teal', 'rose', 'orange', 'green'];
  let hash = 2166136261;
  for (const character of String(value || 'general')) hash = Math.imul(hash ^ character.codePointAt(0), 16777619) >>> 0;
  return identities[hash % identities.length];
}
