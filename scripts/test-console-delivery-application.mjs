#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { createConsoleServer } from './console-server.mjs';
import { registerRoutineContract, saveExecutorBinding, writeRoutineRunReceipt } from './lib/routine-protocol.mjs';
const example = name => JSON.parse(readFileSync(new URL(`../protocol/examples/${name}.v1.json`, import.meta.url)));
const root = mkdtempSync(join(tmpdir(), 'fictional-console-application-'));
const write = (ref, text) => { const path = join(root, ref); mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, typeof text === 'string' ? text : JSON.stringify(text)); };
const now = new Date('2026-08-24T12:00:00.000Z');
let probes = 0, models = 0;
let instance;
try {
  write('VERSION', 'fixture\n'); write('COMECE-AQUI.md', '# Fictional fixture\n');
  write('.cerebro/layout.json', { version: 3, vault: { daily: 'journal' } });
  write('.cerebro/private-ignore.manifest', '.cerebro/runtime\noperacao/execucoes/\n');
  const routine = example('routine-contract'); routine.context.access_requests = [];
  routine.destination = { kind: 'runtime-output', ref: 'routine-output' };
  registerRoutineContract(root, routine); saveExecutorBinding(root, example('executor-binding'));
  write(routine.context.prompt_ref, 'Produce a fictional report in the response only.');
  const receipt = example('routine-run-receipt'); receipt.output_ref = '.cerebro/runtime/outputs/routines/fictional-report.md';
  write(receipt.output_ref, '# Fictional report\n\nDocument review completed.\n'); writeRoutineRunReceipt(root, receipt);
  const target = 'journal/2026-08-24.md';
  const original = '---\ntype: Note\n---\n\n# Manual fictional daily\n\nKeep this manual paragraph.\n'; write(target, original);
  instance = createConsoleServer({ root, clock: () => now,
    executorObserver: () => { probes++; return { status: 'ready', observed_at: now.toISOString() }; },
    spawn: () => { models++; throw Error('model-must-not-run'); } });
  await new Promise(resolve => instance.server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${instance.server.address().port}`;
  const page = await fetch(base); await page.text(); const cookie = page.headers.get('set-cookie').split(';')[0];
  const session = await (await fetch(base+'/api/session', { headers: { Cookie: cookie } })).json();
  const headers = { Origin: base, Cookie: cookie, 'Content-Type': 'application/json', 'X-Cerebro-CSRF': session.csrf_token };
  const get = ref => fetch(base+ref, { headers: { Cookie: cookie } });
  const post = async (ref, payload, overrides = {}) => fetch(base+ref, { method: 'POST', headers: { ...headers, ...overrides }, body: JSON.stringify(payload) });
  const prefix = `/api/runs/${receipt.receipt_id}/application`;
  assert.equal((await fetch(base+prefix)).status, 403, 'private application metadata requires the local session');
  const detail = await (await get(`/api/runs/${receipt.receipt_id}/output`)).json();
  const actor = { approved_by: 'role-reviewer', confirm: true };
  const beforeApproval = await post(prefix+'/preview', { ...actor, target_date: '2026-08-24' });
  assert.equal(beforeApproval.status, 400, 'an unapproved report cannot be applied');
  const approve = await post(`/api/runs/${receipt.receipt_id}/judgments`, { ...actor, verdict: 'approved', action_intent: 'none', note: '', reviewed_sha256: detail.review.content_sha256 });
  assert.equal(approve.status, 200);
  const meta = await get(prefix); assert.equal(meta.status, 200);
  const metadata = await meta.json(); assert.equal(metadata.eligible, true); assert.equal(JSON.stringify(metadata).includes('Keep this manual'), false);
  const noCsrf = await post(prefix+'/preview', { ...actor, target_date: '2026-08-24' }, { 'X-Cerebro-CSRF': '' }); assert.equal(noCsrf.status, 403);
  const previewResponse = await post(prefix+'/preview', { ...actor, target_date: '2026-08-24' });
  assert.equal(previewResponse.status, 200); const preview = await previewResponse.json();
  assert.match(preview.diff, /Fictional report/); assert.equal(readFileSync(join(root,target),'utf8'), original, 'preview cannot write the note');
  const confirm = { ...actor, target_date: preview.target_date, previewed_at: preview.previewed_at, plan_digest: preview.plan_digest };
  assert.equal((await post(prefix+'/apply', { ...confirm, confirm: false })).status, 400);
  write(target, original+'\nA concurrent manual edit.\n');
  assert.equal((await post(prefix+'/apply', confirm)).status, 400, 'changing the note invalidates the displayed preview');
  write(target, original);
  const fresh = await (await post(prefix+'/preview', { ...actor, target_date: '2026-08-24' })).json();
  const appliedResponse = await post(prefix+'/apply', { ...actor, target_date: fresh.target_date, previewed_at: fresh.previewed_at, plan_digest: fresh.plan_digest });
  assert.equal(appliedResponse.status, 200); const applied = await appliedResponse.json();
  const after = readFileSync(join(root,target),'utf8'); assert.match(after, /Keep this manual paragraph/); assert.match(after, /<!-- ai:start -->/); assert.match(after, /Fictional report/);
  const state = await (await get(prefix)).json();
  const applicationId = state.state.application_id || applied.application_id;
  assert(applicationId);
  const rollback = await post(prefix+'/rollback', { ...actor, application_id: applicationId, reason: 'mistake' });
  assert.equal(rollback.status, 200); assert.equal(readFileSync(join(root,target),'utf8'), original);
  const preflightPath = `/api/routines/${routine.routine_id}/preflight`;
  assert.equal((await fetch(base+preflightPath)).status, 403);
  const inspected = await get(preflightPath); assert.equal(inspected.status, 200); assert.equal(probes,0,'opening readiness does not probe or call the model');
  const verified = await post(preflightPath+'/verify', { confirm: true }); assert.equal(verified.status,200); assert.equal(probes,1);
  assert.equal(models,0);
  console.log('✓ authenticated preview/apply/rollback preserve manual notes and conflicts; preflight verification never invokes the model');
} finally { if(instance) await new Promise(resolve=>instance.server.close(resolve)); rmSync(root,{recursive:true,force:true}); }
